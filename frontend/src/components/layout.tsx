import { useEffect, useId, useRef, useState, type ReactNode } from 'react'
import { Link, NavLink, useLocation } from 'react-router-dom'
import type { Meta } from '../lib/api'
import { useConnection } from '../lib/hooks'
import { Icon } from './Icons'
import { Wordmark } from './Logo'
import { Chip } from './status'

export interface NavItem {
  to: string
  label: string
  icon: () => ReactNode
  end?: boolean
  group: 'assurance' | 'operations'
  badge?: number
  attention?: boolean
}

export function Sidebar({ items, meta, open, onClose }: { items: NavItem[]; meta: Meta | null; open: boolean; onClose: () => void }) {
  const loc = useLocation()
  const first = useRef(true)
  useEffect(() => {
    // close the off-canvas drawer after navigating (not on initial mount)
    if (first.current) {
      first.current = false
      return
    }
    onClose()
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [loc.pathname])
  const section = (g: NavItem['group'], label: string) => (
    <>
      <div className="nav-section">{label}</div>
      {items
        .filter((n) => n.group === g)
        .map((n) => (
          <NavLink key={n.to} to={n.to} end={n.end} className={({ isActive }) => (isActive ? 'active' : '')} title={n.label}>
            <n.icon />
            <span className="label">{n.label}</span>
            {n.badge !== undefined && n.badge > 0 && <span className={`nav-badge ${n.attention ? 'is-warn' : ''}`}>{n.badge}</span>}
          </NavLink>
        ))}
    </>
  )
  return (
    <aside className="sidebar" id="sidebar" aria-label="Primary">
      <div className="brand-row">
        <Wordmark />
        <button className="btn sm icon ghost menu-btn close" type="button" onClick={onClose} aria-label="Close navigation" hidden={!open}>
          <Icon.close />
        </button>
      </div>
      <nav className="nav" aria-label="Sections">
        {section('assurance', 'Assurance')}
        {section('operations', 'Operations')}
      </nav>
      <div className="sidebar-foot">
        {meta ? (
          <>
            <div>
              <b>{meta.switch.hostname}</b> · {meta.switch.model}
            </div>
            <div>IOS {meta.switch.ios_version} · {meta.switch.management_ip}</div>
            <div className="stack tight" style={{ marginTop: 6 }}>
              <span>Dataset day {meta.dataset.day} (UTC)</span>
              <span>SentinelSwitch {meta.version}</span>
            </div>
          </>
        ) : (
          <div>connecting…</div>
        )}
      </div>
    </aside>
  )
}

const API_LABEL = { checking: 'API checking', reachable: 'API reachable', errors: 'API errors', unreachable: 'API unreachable' } as const
const STREAM_LABEL = { live: 'events live', connecting: 'events connecting', reconnecting: 'events reconnecting', unsupported: 'events off' } as const

function ago(s: number | null) {
  if (s === null) return 'no response yet'
  if (s < 60) return `last response ${s} s ago`
  return `last response ${Math.round(s / 60)} min ago`
}

export function Topbar({ crumbs, meta, onMenu }: { crumbs: { label: string; to?: string }[]; meta: Meta | null; onMenu: () => void }) {
  const conn = useConnection()
  const stage = meta?.demo?.stage
  const stageChip = stage === 'contained' ? { kind: 'contained', text: `${meta?.flagship_incident} contained` } : stage === 'restored' ? { kind: 'resolved', text: `${meta?.flagship_incident} resolved` } : stage ? { kind: 'neutral', text: 'baseline' } : null
  return (
    <header className="topbar">
      <button className="btn sm icon ghost menu-btn" type="button" onClick={onMenu} aria-label="Open navigation" aria-controls="sidebar">
        <Icon.menu />
      </button>
      <nav className="crumbs" aria-label="Breadcrumb">
        {crumbs.map((c, i) => (
          <span key={i} className={i === crumbs.length - 1 ? 'leaf' : ''}>
            {i > 0 && <span className="sep">/</span>}
            {c.to && i < crumbs.length - 1 ? <Link to={c.to}>{c.label}</Link> : c.label}
          </span>
        ))}
      </nav>
      <span className="chip sim env" title="All telemetry is synthetic and generated by the digital twin">
        Simulation
      </span>
      <div className="spacer" />
      <div className="meta">
        {stageChip && (
          <span className="tb-item hide-mobile" title="Current state of the demo on the switch twin (not the playback position)">
            <span className="tb-k">demo now</span>
            <Chip kind={stageChip.kind} className="stage">
              {stageChip.text}
            </Chip>
          </span>
        )}
        <span className={`conn api-${conn.api}`} title={`API: ${ago(conn.sinceOkS)} (client clock)${conn.lastError ? ` · last error: ${conn.lastError}` : ''}`}>
          <span className="dot" aria-hidden="true" />
          {API_LABEL[conn.api]}
        </span>
        <span className={`conn stream-${conn.stream} hide-mobile`} title="Server-sent event stream: views refresh when the server announces a change">
          <span className="dot" aria-hidden="true" />
          {STREAM_LABEL[conn.stream]}
        </span>
        {meta?.switch.now && (
          <span className="tb-item clock" title="Simulated switch-twin clock (dataset time, UTC). Not the wall clock and not a last-contact time.">
            <span className="tb-k">switch clock</span>
            <span className="mono">{meta.switch.now.replace('T', ' ').slice(0, 16)} UTC</span>
          </span>
        )}
      </div>
    </header>
  )
}

/** Page title row: identity (eyebrow + h1 + optional info popover) left, toolbar right. */
export function PageHeader({ eyebrow, title, info, sub, children, ident }: { eyebrow?: ReactNode; title: ReactNode; info?: ReactNode; sub?: ReactNode; children?: ReactNode; ident?: ReactNode }) {
  return (
    <div className="page-head">
      <div className="heading">
        {eyebrow && <div className="ident-row">{eyebrow}</div>}
        <div className="ident">
          <h1>{title}</h1>
          {ident}
          {info && <InfoPop>{info}</InfoPop>}
        </div>
        {sub && <div className="sub">{sub}</div>}
      </div>
      {children && <div className="toolbar">{children}</div>}
    </div>
  )
}

/** Small "i" button that reveals explanatory text; keyboard accessible, Escape closes. */
export function InfoPop({ children, label = 'About this view' }: { children: ReactNode; label?: string }) {
  const [open, setOpen] = useState(false)
  const id = useId()
  const ref = useRef<HTMLDivElement>(null)
  useEffect(() => {
    if (!open) return
    const onDoc = (e: MouseEvent) => {
      if (!ref.current?.contains(e.target as Node)) setOpen(false)
    }
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') setOpen(false)
    }
    document.addEventListener('mousedown', onDoc)
    document.addEventListener('keydown', onKey)
    return () => {
      document.removeEventListener('mousedown', onDoc)
      document.removeEventListener('keydown', onKey)
    }
  }, [open])
  return (
    <div className="info-pop" ref={ref}>
      <button type="button" aria-label={label} aria-expanded={open} aria-controls={id} onClick={() => setOpen((o) => !o)}>
        <Icon.info />
      </button>
      {open && (
        <div className="pop" id={id} role="note">
          {children}
        </div>
      )}
    </div>
  )
}

/** Section eyebrow with optional count and right-hand controls. */
export function Section({ title, count, right, children, className = '' }: { title: ReactNode; count?: number; right?: ReactNode; children: ReactNode; className?: string }) {
  return (
    <section className={`section ${className}`}>
      <div className="eyebrow">
        <span>{title}</span>
        {count !== undefined && <span className="count">{count}</span>}
        {right && <span className="right">{right}</span>}
      </div>
      {children}
    </section>
  )
}

export function Toolbar({ children, className = '' }: { children: ReactNode; className?: string }) {
  return <div className={`toolbar ${className}`}>{children}</div>
}
