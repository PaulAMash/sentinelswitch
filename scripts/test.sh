#!/usr/bin/env bash
# Backend tests, frontend type-check and linters. Writes a results summary to
# artifacts/sentinelswitch-2.0/validation/test-results.md so the portfolio package cites executed runs.
set -uo pipefail
cd "$(dirname "$0")/.."
OUT=artifacts/sentinelswitch-2.0/validation/test-results.md
mkdir -p "$(dirname "$OUT")"
rc=0
{
  echo "# Test results"
  echo
  echo "Generated by scripts/test.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ) (wall clock) from a local run."
  echo
  echo '## Backend (pytest)'
  echo
  echo '```'
  ./.venv/bin/python -m pytest -q -o addopts='' -p no:cacheprovider 2>&1 | tail -n 1 || rc=1
  echo '```'
  echo
  echo '## Python lint (ruff)'
  echo
  echo '```'
  ./.venv/bin/ruff check backend simulator scripts diagrams/source 2>&1 | tail -n 2 || rc=1
  echo '```'
  echo
  echo '## Frontend (tsc + oxlint)'
  echo
  echo '```'
  ( cd frontend && npx tsc -b 2>&1 | tail -n 3 && echo "tsc: ok" && npx oxlint 2>&1 | tail -n 2 && echo "oxlint: ok" ) || rc=1
  echo '```'
  echo
  echo '## Validation harness'
  echo
  echo '```'
  ./.venv/bin/python -m sentinelswitch validate --json 2>/dev/null | ./.venv/bin/python -c "import sys,json; d=json.load(sys.stdin); m=d['metrics']; print(f\"{m['passed']}/{m['scenarios']} scenarios met their expected outcome ({m['contained']} contained, {m['withheld']} withheld by policy)  MTTD {m['mttd']} s  MTTA {m['mtta']} s  MTTC {m['mttc']} s (simulated clock)\")" || rc=1
  echo '```'
} | tee "$OUT"
exit $rc
